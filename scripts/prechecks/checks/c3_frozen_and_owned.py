"""C3 frozen-and-owned: frozen and owned artifacts, and the history, between the effective base and head.

Rules (DESIGN 3.3). Authorization is read from main, never from the branch and never from a commit message.

  R1 out-of-scope-edit        a changed path outside the manifest's owns/appends (needs a declared `owns`)
  R2 shared-file-shape        a shared file changed by more than its allowed additive shape
  R3 frozen-edit              a frozen path differs from base with no authorized entry
  R4 assertion-weakened       a base-present gate script lost or loosened an assertion, or a mutant/control list shrank
  R5 coverage-dropped         a count or name list in a base-present receipt shrank
  R6 frozen-row-changed       a row of a declared frozen data file changed (additions are allowed)
  R7 freeze-order / provenance-mismatch
  R8 generator-not-reproducible   (declared generators only)
  R9 normalized-comparison
  R10 history lints (trailer, red wording, census approval summary, mixed-gate commit)
  R11 red-tip                 census:test / census --check fail at head
"""
from __future__ import annotations

