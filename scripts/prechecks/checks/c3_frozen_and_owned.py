def history(ctx) -> list[Condition]:
    found = []
    family = {'claude': 'claude', 'codex': 'codex|gpt'}.get(str(ctx.manifest.executor()).lower(), str(ctx.manifest.executor()).lower())
    merge_as_unit = bool(ctx.manifest.get('merge_as_unit', False))
    readme = ctx.head.text(f'tests/compiler-{ctx.inc}/README.md') if ctx.inc else None
    if readme and re.search(r'merge as a unit', readme, re.I):
        merge_as_unit = True
    for commit in ctx.commits():
        if commit.is_merge:
            continue
        trailers = re.findall(r'(?im)^co-authored-by:\s*(.+)$', commit.body)
        if not any(re.search(family, t, re.I) for t in trailers):
            found.append(Condition(ID, 'commit-trailer', 'minor', {'commit': commit.sha}, actor='coordinator',
                                   expected=f'every non-merge commit carries a Co-Authored-By trailer naming the executor ({ctx.manifest.executor()})',
                                   observed=f'{commit.sha[:8]} {commit.subject[:60]!r}: '
                                            + ('no Co-Authored-By trailer' if not trailers else f'trailer names {trailers[0][:40]!r}')))
        if RED_WORDING.search(commit.body) and not merge_as_unit:
            found.append(Condition(ID, 'red-commit-wording', 'info', {'commit': commit.sha}, actor='coordinator',
                                   expected='intermediate red commits are declared as a unit in the README',
                                   observed=f'{commit.sha[:8]} says the gate is red at this commit'))
        files = ctx.repo.commit_files(commit.sha)
        if any(f.path == 'tools/census/approved.json' for f in files) and 'census:approve' not in commit.body:
            found.append(Condition(ID, 'census-approval-summary', 'minor', {'commit': commit.sha}, actor='coordinator',
                                   expected='a commit that changes approved.json carries the census:approve summary',
                                   observed=f'{commit.sha[:8]} edits approved.json without the summary'))
        other_gate = [f.path for f in files if GATE_SCRIPT.match(f.path) and not ctx.manifest.is_owned(f.path)
                      and f.status in 'MR' and not f.path.startswith('scripts/gates/')]
        if other_gate and any(f.path.startswith('src/') and f.path.endswith('.bend') for f in files):
            found.append(Condition(ID, 'mixed-gate-commit', 'info', {'commit': commit.sha}, actor='coordinator',
                                   expected='a commit does not change another gate\'s check script together with src/*.bend',
                                   observed=f'{commit.sha[:8]} touches {other_gate[0]} and src/*.bend'))
    return found


