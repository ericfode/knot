def red_tip(ctx) -> tuple[list[Condition], str]:
    export = ctx.export(ctx.head)
    if not (export / 'tools/census/census.mjs').exists():
        return [], 'no tools/census in this tree'
    found = []
    code, out, err = ctx.run(['node', 'tools/census/census.mjs', '--check'], cwd=export, timeout=60)
    if code is None:
        return [], 'census --check timed out or node is missing'
    if code != 0:
        found.append(Condition(ID, 'red-tip', 'major', {'command': 'census --check'}, expected='census --check passes at head',
                               observed=(err or out).decode(errors='replace').strip().splitlines()[-1][:160] if (err or out) else f'exit {code}',
                               fix_hint='Run `npm run census` and review the approval policy.'))
    if (export / 'tools/census/tests').is_dir():
        tests = sorted(p.name for p in (export / 'tools/census/tests').glob('*.test.mjs'))
        code, out, err = ctx.run(['node', '--test', *[f'tools/census/tests/{t}' for t in tests]], cwd=export, timeout=120)
        if code not in (0, None):
            failed = re.findall(r'(?m)^not ok \d+ - (.+)$', out.decode(errors='replace'))
            found.append(Condition(ID, 'red-tip', 'major', {'command': 'census:test'}, value={'failed': len(failed)},
                                   expected='npm run census:test passes at head',
                                   observed=f'{len(failed)} failing test(s): {failed[:2]}',
                                   fix_hint='census:test is not a registered gate, so nothing else catches this.'))
        elif code is None:
            return found, 'census:test timed out'
    return found, ''


def run(ctx) -> CheckResult:
    result = CheckResult()
    if ctx.base is None:
        return CheckResult(outcome='not-applicable', reason='no base to compare against')
    rules = [('out-of-scope-edit', out_of_scope), ('shared-file-shape', shared_shape), ('frozen-edit', frozen_edits),
             ('assertion-weakened', assertion_weakening), ('coverage-dropped', coverage_dropped),
             ('frozen-row-changed', frozen_rows), ('freeze-order', freeze_order),
             ('normalized-comparison', normalized_comparison), ('history', history)]
    if not ctx.manifest.declared_owns:
        result.rules_unavailable['out-of-scope-edit'] = 'no `owns` declared in the increment manifest'
        rules = [r for r in rules if r[0] != 'out-of-scope-edit']
    if ctx.identity and not ctx.commits():
        return CheckResult(outcome='pass', reason='identity: nothing changed since base', rules_run=[])
    for name, fn in rules:
        result.conditions += fn(ctx)
        result.rules_run.append(name)
    found, reason = generators(ctx)
    result.conditions += found
    if reason:
        result.rules_unavailable['generator-not-reproducible'] = reason
    else:
        result.rules_run.append('generator-not-reproducible')
    if ctx.options.get('census', True) and not ctx.identity and any(
            p.startswith(('src/', 'tools/census/', 'docs/compiler-campaign/inventory/')) for p in ctx.changed_paths() + ctx.deleted_paths()):
        found, reason = red_tip(ctx)
        result.conditions += found
        if reason:
            result.rules_unavailable['red-tip'] = reason
        else:
            result.rules_run.append('red-tip')
    return result


CHECK = Check(ID, 'frozen-and-owned', 'frozen and owned artifacts and the history since the base', run, budget=15)
