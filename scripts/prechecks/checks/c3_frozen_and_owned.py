def generators(ctx) -> tuple[list[Condition], str]:
    declared = ctx.manifest.get('generators', []) or []
    if not declared:
        return [], 'no generators declared in the manifest'
    import subprocess
    found = []
    export = ctx.export(ctx.head)
    scratch = ctx.scratch / 'generators'
    scratch.mkdir(parents=True, exist_ok=True)
    for generator in declared:
        cmd = generator.get('cmd') or []
        outputs = generator.get('outputs') or []
        code, _out, err = ctx.run(cmd, cwd=export, timeout=10)
        if code != 0:
            found.append(Condition(ID, 'generator-not-reproducible', 'minor', {'path': ' '.join(cmd)}, actor='executor',
                                   observed=f'generator exited {code}: {err.decode(errors="replace")[:120]}',
                                   expected='a touched generator reruns and reproduces its tracked output'))
            continue
        for output in outputs:
            produced = (export / output).read_bytes() if (export / output).exists() else None
            tracked = ctx.head.read(output)
            if produced != tracked:
                found.append(Condition(ID, 'generator-not-reproducible', 'minor', {'path': output}, actor='executor',
                                       expected='rerunning the generator reproduces the tracked file',
                                       observed=f'{output} differs after rerunning {" ".join(cmd)}',
                                       fix_hint='Regenerate and commit, or fix the generator.'))
    return found, ''


