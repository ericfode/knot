def normalized_comparison(ctx) -> list[Condition]:
    found = []
    plan, expected = 'vm/golden/plan.json', 'vm/golden/expectations.json'
    if ctx.head.has(plan) and ctx.head.has(expected):
        try:
            p, e = json.loads(ctx.head.text(plan)), json.loads(ctx.head.text(expected))
        except ValueError:
            p = e = None
        rows = lambda doc: {r.get('name'): r.get('seed_stdout') for r in (doc if isinstance(doc, list) else doc.get('goldens', doc.get('rows', [])))
                            if isinstance(r, dict)} if doc is not None else {}
        a, b = rows(p), rows(e)
        differing = sorted(n for n in set(a) & set(b) if a[n] != b[n])
        if differing:
            found.append(Condition(ID, 'normalized-comparison', 'minor', {'path': plan}, value={'rows': len(differing)},
                                   expected='seed_stdout is byte-identical in the plan and the expectations',
                                   observed=f'{len(differing)} row(s) differ, e.g. {differing[:3]}'))
    pattern = re.compile(r"seed\w*[^\n]*\.(?:replace|strip|lstrip|rstrip)\(|\.(?:replace|strip)\([^\n]*\)[^\n]*seed_stdout")
    for change in ctx.changes():
        if change.status in 'AMR' and GATE_SCRIPT.match(change.path):
            patch = ctx.repo.patch(ctx.base.treeish, ctx.head.treeish, [change.path], unified=0)
            for hunk in diffs.parse(patch).get(change.path, []):
                for line in hunk.added:
                    if pattern.search(line):
                        found.append(Condition(ID, 'normalized-comparison', 'minor', {'path': change.path, 'text': _sha(line)},
                                               expected='seed values are compared byte for byte',
                                               observed=f'seed value compared through a normalization: {line.strip()[:100]}'))
    return found


