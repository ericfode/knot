#!/usr/bin/env python3
"""Freeze or verify the self-hosting joint suite against the pinned seed, on two lanes.

    python3 tests/compiler-selfhost/regen.py            # verify (default; `verify` is accepted)
    python3 tests/compiler-selfhost/regen.py --write    # rewrite the observations section

Every seed observation is taken on both of the seed's oracle lanes:

- `interpreter`: `bun main.ts <file>`, the reference interpreter;
- `native`: `bun main.ts <file> -o <bin>` (clang), then `<bin>`, the lane C1 is built on.

A lane disagreement is never averaged away. It passes only when a hand-reviewed
`lane_decisions` entry names it (DEC-7); an unreviewed one fails.

Check mode recomputes every observation and the generated scale fixtures, then
compares them with `expectations.json` exactly. `--write` rewrites only the
`observations` section and the generated fixtures. The hand-reviewed sections
(`needs`, `cases`, `lane_decisions`) are never changed here; they are validated
against the seed's classification. Nothing here runs or reads Knot.

Commands run from the repository root with relative paths, so recorded argv and
output are identical in every checkout. Builds, wrappers and sandboxes live in
the ignored `.local/compiler-selfhost/seed/`, which is cleared first.
"""
