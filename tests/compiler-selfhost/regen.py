class Mismatch(Exception):
    pass


def require(condition, detail):
    if not condition:
        raise Mismatch(detail)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def env():
    return {**os.environ, 'BEND_NO_TELEMETRY': '1'}


def execute(argv, cwd=ROOT):
    try:
        p = subprocess.run([str(a) for a in argv], cwd=cwd, env=env(), stdin=subprocess.DEVNULL,
                           capture_output=True, timeout=TIMEOUT)
    except subprocess.TimeoutExpired:
        raise Mismatch(('a seed timeout is exhaustion of the harness, not an observation', argv))
    out = {'argv': [str(a) for a in argv], 'exit': p.returncode,
           'stdout': p.stdout.decode(), 'stderr': p.stderr.decode()}
    return out


HOST_TOOLCHAIN = 'bend needs clang'


def build(argv):
    """A native build. The seed's clang probe can fail to spawn under host load;
    that is a host failure, never an observation: retry it, then abort."""
    for _ in range(3):
        built = execute(argv)
        if not (built['exit'] != 0 and HOST_TOOLCHAIN in built['stderr'] and 'found no clang' in built['stderr']):
            return built
    raise Mismatch(('host failure: the seed found no clang three times', built))


# ---------------------------------------------------------------- scale bundle

def scale_bundle() -> dict[str, str]:
    """Twenty modules plus an entry and Base: 782 functions, a 720-link chain.

    Module k defines links `s{k}_0 .. s{k}_35` and conversions to and from
    module k-1's Flag; `s{k}_0` calls module k-1's last link, so the entry
    reaches every link through one call. A link inverts its flag where
    (k + i) % 3 == 0, so the result depends on the whole chain.
    """
    files = {}
    width, depth = 20, 36
    for k in range(width):
        lines = ['# Generated by regen.py (scale-bundle); do not edit.', 'import Base']
        if k:
            lines.append(f'import ./m{k - 1:02}.bend as P')
        lines += ['', 'type Flag is Data:', '  Off{}', '  On{}', '']
        lines += ['def flip(x: Flag) -> Flag:', '  match x:', '    case Off{}: On{}', '    case On{}: Off{}', '']
        if k:
            lines += ['def lift(x: P.Flag) -> Flag:', '  match x:', '    case P.Off{}: Off{}',
                      '    case P.On{}: On{}', '', 'def lower(x: Flag) -> P.Flag:', '  match x:',
                      '    case Off{}: P.Off{}', '    case On{}: P.On{}', '']
        for i in range(depth):
            if i == 0:
                body = f'lift(P.s{k - 1}_{depth - 1}(lower(x)))' if k else 'x'
            else:
                body = f'flip(s{k}_{i - 1}(x))' if (k + i) % 3 == 0 else f's{k}_{i - 1}(x)'
            lines += [f'def s{k}_{i}(x: Flag) -> Flag:', f'  {body}', '']
        files[f'scale-bundle/m{k:02}.bend'] = '\n'.join(lines).rstrip('\n') + '\n'
    last = width - 1
    files['scale-bundle/main.bend'] = '\n'.join([
        '# Generated by regen.py (scale-bundle); do not edit.',
        '# 782 functions across 20 modules plus Base: one 720-link call chain.',
        'import Base', f'import ./m{last:02}.bend as M', '',
        'type Answer is Type:', '  No{}', '  Yes{}', '',
        'type Seed is Type:', '  Low{}', '  High{}', '',
        'def answer(x: M.Flag) -> Answer:',
        '  match x:', '    case M.Off{}: No{}', '    case M.On{}: Yes{}', '',
        'def start(s: Seed) -> M.Flag:', '  match s:', '    case Low{}: M.Off{}', '    case High{}: M.On{}', '',
        'def through(s: Seed) -> Answer:', f'  answer(M.s{last}_{depth - 1}(start(s)))', '',
        'def main() -> Answer:', '  through(High{})', ''])
    return files


def scale_catalog() -> dict[str, str]:
    """One Base-free book of 723 functions: the catalog limit without modules."""
    count = 720
    lines = ['# Generated by regen.py (scale-catalog); do not edit.',
             '# 723 functions in one book, past the 256-function catalog limit.', '',
             'type Flag is Type:', '  Off{}', '  On{}', '',
             'def flip(x: Flag) -> Flag:', '  match x:', '    case Off{}: On{}', '    case On{}: Off{}', '']
    for i in range(count):
        body = 'x' if i == 0 else (f'flip(c{i - 1}(x))' if i % 7 == 0 else f'c{i - 1}(x)')
        lines += [f'def c{i}(x: Flag) -> Flag:', f'  {body}', '']
    lines += ['def through(x: Flag) -> Flag:', f'  c{count - 1}(x)', '',
              'def main() -> Flag:', '  through(On{})', '']
    return {'scale-catalog/main.bend': '\n'.join(lines)}


